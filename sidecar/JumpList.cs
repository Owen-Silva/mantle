    /// The shortcut Windows itself would start this app from (the resolver's best one for the
    /// AppID: a Start menu .lnk with its arguments), for "new window" on a running app that is not
    /// pinned and for a pin Mantle adds itself. Owen's browser is why: its exe is a bare
    /// electron.exe, which started alone opens nothing of his.
    static object DoShortcut(Dictionary<string, object> req) {
      string how;
      string appid = ResolveAppId(req, out how);
      return Json.Obj("ok", true, "appid", appid, "how", how, "shortcut", BestShortcut(appid));
    }

    static string BestShortcut(string appid) {
      IntPtr psi;
      int hr = Resolver().GetBestShortcutForAppID(appid, out psi);
      if (hr != 0 || psi == IntPtr.Zero) return null;
      object o = null;
      try {
        o = Marshal.GetObjectForIUnknown(psi);
        var si = o as IShellItem;
        if (si == null) return null;
        IntPtr p;
        si.GetDisplayName(0x80058000, out p);   // SIGDN_FILESYSPATH
        return TakeString(p);
      } catch (Exception) {
        return null;
      } finally {
        if (o != null) Marshal.ReleaseComObject(o);
        Marshal.Release(psi);
      }
    }

    /// "A new window" of the app itself: its best shortcut, else its exe, else (a Store app) its
    /// AppsFolder entry. The same ShellExecute Explorer runs for a double-clicked shortcut.
    static object LaunchApp(Dictionary<string, object> req, bool dry) {
      string how;
      string appid = ResolveAppId(req, out how);
      string target = BestShortcut(appid), route = "its shortcut";
      if (target == null && appid.IndexOf('!') > 0) { target = @"shell:AppsFolder\" + appid; route = "its Store app entry"; }
      // after the Store entry: a packaged app's exe under WindowsApps cannot be started directly
      if (target == null && !string.IsNullOrEmpty(Json.GetString(req, "exe"))) { target = Json.GetString(req, "exe"); route = "its program file"; }
      if (target == null) throw new InvalidOperationException("Windows knows no shortcut for " + appid + " and Mantle was given no program file to start");
      if (dry) return Json.Obj("ok", true, "dryRun", true, "route", route, "target", Path.GetFileName(target), "appid", appid);
      var sei = new SHELLEXECUTEINFO();
      sei.cbSize = Marshal.SizeOf(typeof(SHELLEXECUTEINFO));
      sei.fMask = 0x00000400;   // SEE_MASK_FLAG_NO_UI
      sei.lpFile = target;
      sei.nShow = 1;
      if (!N.ShellExecuteExW(ref sei))
        throw new InvalidOperationException("Windows would not start " + Path.GetFileName(target) + " (error " + Marshal.GetLastWin32Error() + ")");
      return Json.Obj("ok", true, "route", route, "target", Path.GetFileName(target));
    }

