    static IStorage OpenCompound(byte[] b, out IntPtr hglobal) {
      hglobal = N.GlobalAlloc(0x0002, new UIntPtr((uint)b.Length));   // GMEM_MOVEABLE
      if (hglobal == IntPtr.Zero) throw new InvalidDataException("out of memory for a " + b.Length + "-byte copy");
      IntPtr p = N.GlobalLock(hglobal);
      Marshal.Copy(b, 0, p, b.Length);
      N.GlobalUnlock(hglobal);
      IntPtr lb;
      int hr = N.CreateILockBytesOnHGlobal(hglobal, true, out lb);
      if (hr != 0) { N.GlobalFree(hglobal); hglobal = IntPtr.Zero; throw new InvalidDataException("no lock bytes (0x" + hr.ToString("x8") + ")"); }
      hglobal = IntPtr.Zero;   // owned by the lock bytes now
      try {
        IStorage stg;
        hr = N.StgOpenStorageOnILockBytes(lb, IntPtr.Zero, 0x10, IntPtr.Zero, 0, out stg);   // STGM_READ | STGM_SHARE_EXCLUSIVE
        if (hr != 0 || stg == null) throw new InvalidDataException("not a compound file (0x" + hr.ToString("x8") + ")");
        return stg;
      } finally {
        Marshal.Release(lb);   // the storage keeps its own reference
      }
    }

    static byte[] ReadAll(IStream s) {
      var ms = new MemoryStream();
      var buf = new byte[65536];
      IntPtr got = Marshal.AllocHGlobal(4);
      try {
        while (true) {
          s.Read(buf, buf.Length, got);
          int n = Marshal.ReadInt32(got);
          if (n <= 0) break;
          ms.Write(buf, 0, n);
          if (ms.Length > 16 * 1024 * 1024) throw new InvalidDataException("a stream is larger than 16 MB");
        }
      } finally { Marshal.FreeHGlobal(got); }
      return ms.ToArray();
    }

    /// DestList layout (versions 3 and 4, Windows 10/11; libyal's "Jump lists format" and checked
    /// against every automatic file on Owen's machine by sidecar/test-jumplist.js): a 32-byte header
    /// (version, entries, pinned entries, ...), then per entry: 88 bytes of droids and host name,
    /// entry number @88, a float score @100... see the offsets below.
    static List<Item> ReadAutomatic(string path, bool keep, out string info) {
      byte[] b = ReadShared(path);
      IntPtr hg;
      IStorage stg = OpenCompound(b, out hg);
      var items = new List<Item>();
      try {
        IStream ds;
        int hr = stg.OpenStream("DestList", IntPtr.Zero, 0x10, 0, out ds);
        // STG_E_FILENOTFOUND: Windows writes the file before the app's first recent item (or after
        // "clear"), with no DestList yet. That is an EMPTY list, not a broken one (quality pass,
        // 2026-09-29: an Electron app's file on Owen's machine read as an error with a hex code).
        if (hr == unchecked((int)0x80030002)) { info = "empty (no DestList yet)"; return items; }
        if (hr != 0 || ds == null) throw new InvalidDataException("its recent-items file is damaged (no list inside it)");
        byte[] d;
        try { d = ReadAll(ds); } finally { Marshal.ReleaseComObject(ds); }
        if (d.Length < 32) throw new InvalidDataException("its DestList is " + d.Length + " bytes");
        int version = BitConverter.ToInt32(d, 0);
        int entries = BitConverter.ToInt32(d, 4);
        if (entries < 0 || entries > 5000) throw new InvalidDataException("its DestList claims " + entries + " entries");
        bool v1 = version < 3;
        int pos = 32, missing = 0;
        for (int e = 0; e < entries; e++) {
          int fixedLen = v1 ? 114 : 130;
          Need(d, pos, fixedLen);
          int num = BitConverter.ToInt32(d, pos + 88);
          float score = BitConverter.ToSingle(d, pos + 96);
          long used = BitConverter.ToInt64(d, pos + 100);
          int pin = BitConverter.ToInt32(d, pos + 108);
          uint count = v1 ? 0u : BitConverter.ToUInt32(d, pos + 116);
          int plen = BitConverter.ToUInt16(d, pos + fixedLen - 2);
          Need(d, pos + fixedLen, plen * 2 + (v1 ? 0 : 4));
          pos += fixedLen + plen * 2 + (v1 ? 0 : 4);

          IStream es;
          hr = stg.OpenStream(num.ToString("x"), IntPtr.Zero, 0x10, 0, out es);
          if (hr != 0 || es == null) { missing++; continue; }
          byte[] lnk;
          try { lnk = ReadAll(es); } finally { Marshal.ReleaseComObject(es); }
          object obj = new ShellLink();
          try {
            IStream ms = N.SHCreateMemStream(lnk, (uint)lnk.Length);
            try { ((IPersistStream)obj).Load(ms); } finally { Marshal.ReleaseComObject(ms); }
            Item it = DescribeItem((IShellLinkW)obj, lnk);
            it.Token = "a:" + num;
            it.Pinned = pin >= 0;
            it.PinAt = pin;
            it.Score = score;
            it.Used = used;
            it.Count = count;
            it.CanRemove = !it.Pinned;
            if (keep) { it.Obj = obj; obj = null; }
            items.Add(it);
          } catch (Exception) {
            missing++;
          } finally {
            if (obj != null) Marshal.ReleaseComObject(obj);
          }
        }
        info = "v" + version + ", " + entries + " entries" + (missing > 0 ? ", " + missing + " unreadable" : "");
      } finally {
        Marshal.ReleaseComObject(stg);
      }
      return items;
    }

    /// A recent/frequent/pinned item: a file or folder the app opened. Named the way Explorer
    /// names it, iconed by type unless it is on a local fixed drive.
    static Item DescribeItem(IShellLinkW link, byte[] raw) {
      var it = new Item { Kind = "item" };
      IntPtr pidl = IntPtr.Zero;
      try {
        link.GetIDList(out pidl);
        string parsing = pidl != IntPtr.Zero ? PidlName(pidl, Win32.SIGDN_DESKTOPABSOLUTEPARSING) : null;
        it.Title = pidl != IntPtr.Zero ? PidlName(pidl, Win32.SIGDN_NORMALDISPLAY) : null;
        var sb = new StringBuilder(1040);
        if (string.IsNullOrEmpty(parsing)) { try { link.GetPath(sb, sb.Capacity, IntPtr.Zero, 0x4); parsing = sb.ToString(); } catch (Exception) { } }
        if (string.IsNullOrEmpty(it.Title)) it.Title = string.IsNullOrEmpty(parsing) ? "(unnamed)" : Path.GetFileName(parsing.TrimEnd('\\'));
        it.Tip = parsing;
        // FileAttributes sit in the link header at 0x18: no disk access to tell a folder.
        bool folder = raw.Length >= 0x1C && (BitConverter.ToUInt32(raw, 0x18) & 0x10) != 0;
        if (IsLocal(parsing) && !folder) {
          string ext = (Path.GetExtension(parsing) ?? "").ToLowerInvariant();
          // Types whose icon is the file's own (programs, shortcuts, icons) are read per file.
          if (ext == ".exe" || ext == ".lnk" || ext == ".ico" || ext == ".url") it.Icon = IconFor("", 0, parsing, pidl);
        }
        if (it.Icon == null) {
          if (parsing != null && (parsing.StartsWith("::") || parsing.StartsWith("shell:"))) it.Icon = FromPidl(pidl);
          else it.Icon = ByType(parsing ?? "", folder);
        }
      } finally {
        if (pidl != IntPtr.Zero) Win32.CoTaskMemFree(pidl);
      }
      return it;
    }

