    /// Loads the ONE item a token names, from the files as they are now. The caller releases Obj.
    static Item Find(Dictionary<string, object> req, out string appid, out string how) {
      appid = ResolveAppId(req, out how);
      string token = Json.GetString(req, "item") ?? "";
      string hash = HashOf(appid);
      string dir = RecentDir(req);
      Item found = null;
      if (token.StartsWith("c:")) {
        var cats = ReadCustom(Path.Combine(dir, "CustomDestinations", hash + ".customDestinations-ms"), new List<int>(), true);
        foreach (var c in cats) if (c.Value != null) foreach (Item i in c.Value) {
          if (i.Token == token && found == null) found = i;
          else if (i.Obj != null) Marshal.ReleaseComObject(i.Obj);
        }
      } else if (token.StartsWith("a:")) {
        string info;
        var items = ReadAutomatic(Path.Combine(dir, "AutomaticDestinations", hash + ".automaticDestinations-ms"), true, out info);
        foreach (Item i in items) {
          if (i.Token == token && found == null) found = i;
          else if (i.Obj != null) Marshal.ReleaseComObject(i.Obj);
        }
      } else throw new InvalidOperationException("jumplist: item must be a token from jumplist.get (c:... or a:...)");
      if (found == null || found.Obj == null)
        throw new InvalidOperationException("that item is no longer in " + appid + "'s jump list (the app rewrote it); open the menu again");
      string title = Json.GetString(req, "title");
      if (!string.IsNullOrEmpty(title) && title != found.Title) {
        Marshal.ReleaseComObject(found.Obj);
        throw new InvalidOperationException("the jump list changed since the menu opened (\"" + title + "\" is now \"" + found.Title + "\"); open the menu again");
      }
      return found;
    }

    static object DoOpen(Dictionary<string, object> req) {
      if ((Json.GetString(req, "item") ?? "") == "app") return LaunchApp(req, Json.GetBool(req, "dry", false));
      string appid, how;
      Item it = Find(req, out appid, out how);
      bool dry = Json.GetBool(req, "dry", false);
      try {
        if (it.Kind == "task" || it.Kind == "link") return InvokeLink(it, dry);
        return OpenItem(it, Json.GetString(req, "exe"), appid, dry);
      } finally {
        Marshal.ReleaseComObject(it.Obj);
      }
    }

    /// A task or a custom-category link runs through the shell link's OWN default command, the
    /// way Explorer runs a .lnk: its arguments, working directory, show command, run-as and the
    /// AppUserModelID it carries all come along, with nothing re-assembled by hand.
    static object InvokeLink(Item it, bool dry) {
      var cm = it.Obj as IContextMenu;
      if (cm == null) throw new InvalidOperationException("\"" + it.Title + "\" cannot be run: Windows gave no command for it");
      IntPtr menu = N.CreatePopupMenu();
      try {
        int hr = cm.QueryContextMenu(menu, 0, 1, 0x7FFF, 0x1);   // CMF_DEFAULTONLY
        if (hr < 0) throw new InvalidOperationException("\"" + it.Title + "\" has no command (0x" + hr.ToString("x8") + ")");
        uint def = N.GetMenuDefaultItem(menu, 0, 0);
        if (def == 0xFFFFFFFF || def < 1) throw new InvalidOperationException("\"" + it.Title + "\" has no default command");
        if (dry) return Json.Obj("ok", true, "dryRun", true, "title", it.Title, "route", "link default command", "command", (int)(def - 1), "tip", it.Tip);
        var ici = new CMINVOKECOMMANDINFO();
        ici.cbSize = Marshal.SizeOf(typeof(CMINVOKECOMMANDINFO));
        ici.fMask = 0x00004000;          // CMIC_MASK_FLAG_NO_UI: the menu has already closed, no error box
        ici.lpVerb = new IntPtr(def - 1);
        ici.nShow = 1;                   // SW_SHOWNORMAL; the link's own show command wins inside
        hr = cm.InvokeCommand(ref ici);
        if (hr < 0) throw new InvalidOperationException("\"" + it.Title + "\" did not start (0x" + hr.ToString("x8") + ")");
        return Json.Obj("ok", true, "title", it.Title, "route", "link default command");
      } finally {
        N.DestroyMenu(menu);
      }
    }

    /// A recent or pinned FILE opens in the app whose list it is in (Windows' rule: a .txt in
    /// Notepad++'s list opens in Notepad++, not in the default editor): that app's association
    /// handler for the extension. With no such handler, the file's default handler, and the reply
    /// says so.
    static object OpenItem(Item it, string exe, string appid, bool dry) {
      var link = (IShellLinkW)it.Obj;
      IntPtr pidl;
      link.GetIDList(out pidl);
      if (pidl == IntPtr.Zero) throw new InvalidOperationException("\"" + it.Title + "\" has no location to open");
      try {
        string ext = Path.GetExtension(it.Tip ?? "");
        IAssocHandler match = null;
        string matchName = null;
        if (!string.IsNullOrEmpty(ext) && (!string.IsNullOrEmpty(exe) || !string.IsNullOrEmpty(appid))) {
          IEnumAssocHandlers en;
          if (N.SHAssocEnumHandlers(ext, 0, out en) == 0 && en != null) {
            try {
              IAssocHandler h; uint got;
              while (match == null && en.Next(1, out h, out got) == 0 && got == 1) {
                string name = null;
                try { h.GetName(out name); } catch (Exception) { }
                if (name != null && ((exe != null && string.Equals(name, exe, StringComparison.OrdinalIgnoreCase)) ||
                                     string.Equals(name, appid, StringComparison.OrdinalIgnoreCase))) { match = h; matchName = name; }
                else Marshal.ReleaseComObject(h);
              }
            } finally { Marshal.ReleaseComObject(en); }
          }
        }
        if (match != null) {
          try {
            if (dry) return Json.Obj("ok", true, "dryRun", true, "title", it.Title, "route", "the app's handler for " + ext, "handler", matchName);
            object si;
            Guid iid = IidShellItem;
            if (Win32.SHCreateItemFromIDList(pidl, ref iid, out si) != 0 || si == null) throw new InvalidOperationException("\"" + it.Title + "\" could not be found");
            try {
              IntPtr dobj;
              Guid bhid = BhidDataObject, did = IidDataObject;
              ((IShellItem)si).BindToHandler(IntPtr.Zero, ref bhid, ref did, out dobj);
              object data = Marshal.GetObjectForIUnknown(dobj);
              Marshal.Release(dobj);
              try { match.Invoke(data); } finally { Marshal.ReleaseComObject(data); }
            } finally { Marshal.ReleaseComObject(si); }
            return Json.Obj("ok", true, "title", it.Title, "route", "the app's handler for " + ext);
          } finally { Marshal.ReleaseComObject(match); }
        }
        string why = string.IsNullOrEmpty(ext) ? "a folder or shell item" : "no " + ext + " handler is registered to this app";
        if (dry) return Json.Obj("ok", true, "dryRun", true, "title", it.Title, "route", "default handler (" + why + ")");
        var sei = new SHELLEXECUTEINFO();
        sei.cbSize = Marshal.SizeOf(typeof(SHELLEXECUTEINFO));
        sei.fMask = 0x0000000C | 0x00000400;   // SEE_MASK_INVOKEIDLIST | SEE_MASK_FLAG_NO_UI
        sei.lpIDList = pidl;
        sei.nShow = 1;
        if (!N.ShellExecuteExW(ref sei))
          throw new InvalidOperationException("\"" + it.Title + "\" did not open (error " + Marshal.GetLastWin32Error() + "); it may have been moved or deleted");
        return Json.Obj("ok", true, "title", it.Title, "route", "default handler (" + why + ")");
      } finally {
        Win32.CoTaskMemFree(pidl);
      }
    }

    /// "Remove from this list": IApplicationDestinations, the documented call, which covers the
    /// Recent and Frequent lists. Tasks and an app's own categories belong to the app (Windows
    /// offers no remove for tasks; for a custom category only the app itself can honour one).
    static object DoRemove(Dictionary<string, object> req) {
      string appid, how;
      Item it = Find(req, out appid, out how);
      try {
        if (!it.Token.StartsWith("a:")) throw new InvalidOperationException("\"" + it.Title + "\" belongs to the app's own list; only the app can remove it");
        if (it.Pinned) throw new InvalidOperationException("\"" + it.Title + "\" is pinned; Windows offers no documented way for another program to unpin it");
        if (Json.GetBool(req, "dry", false)) return Json.Obj("ok", true, "dryRun", true, "title", it.Title, "route", "IApplicationDestinations.RemoveDestination", "appid", appid);
        var ad = (IApplicationDestinations)Activator.CreateInstance(Type.GetTypeFromCLSID(ClsidAppDestinations, true));
        try {
          ad.SetAppID(appid);
          ad.RemoveDestination(it.Obj);
        } finally { Marshal.ReleaseComObject(ad); }
        lock (_cache) _cache.Remove(appid);
        return Json.Obj("ok", true, "title", it.Title, "route", "IApplicationDestinations.RemoveDestination");
      } finally {
        Marshal.ReleaseComObject(it.Obj);
      }
    }
  }
