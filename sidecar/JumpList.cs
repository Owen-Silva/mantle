    /// One STA thread with a queue. If a job has run for more than StuckMs (a recent file on a
    /// dead network share can hang a shell call for a minute), the next request gets a NEW worker
    /// instead of queueing behind it; the stuck one finishes, replies late, and exits.
    sealed class Worker {
      public readonly BlockingCollection<Action> Jobs = new BlockingCollection<Action>();
      public long BusySince;   // Stopwatch ticks, 0 = idle
      public IApplicationResolver8 Resolver;
      public string ResolverError;
      public Worker() {
        var th = new Thread(Loop);
        th.IsBackground = true;
        th.Name = "jumplist";
        th.SetApartmentState(ApartmentState.STA);
        th.Start();
      }
      void Loop() {
        foreach (Action a in Jobs.GetConsumingEnumerable()) {
          Interlocked.Exchange(ref BusySince, Stopwatch.GetTimestamp());
          try { a(); } catch (Exception ex) { Program.EmitLog("warn", "jumplist: a job threw past its own catch: " + ex.Message); }
          Interlocked.Exchange(ref BusySince, 0);
          if (Jobs.IsAddingCompleted && Jobs.Count == 0) break;
        }
      }
    }
    const int StuckMs = 3000;
    static Worker _worker;
    static int _replaced;
    static readonly object _wl = new object();
    [ThreadStatic] static Worker _current;

    static string Defer(Dictionary<string, object> req, ref object result, Func<Dictionary<string, object>, object> work) {
      object rid = req.ContainsKey("id") ? req["id"] : null;
      Worker w;
      lock (_wl) {
        if (_worker != null) {
          long since = Interlocked.Read(ref _worker.BusySince);
          if (since != 0 && Lanes.MsSince(since) > StuckMs) {
            _worker.Jobs.CompleteAdding();
            _worker = null;
            _replaced++;
            Program.EmitLog("warn", "jumplist: a read has been stuck for more than " + StuckMs + " ms; a fresh reader takes the next requests");
          }
        }
        if (_worker == null) _worker = new Worker();
        w = _worker;
      }
      Action job = delegate {
        _current = w;
        object res = null; string err = null;
        try { res = work(req); }
        catch (InvalidOperationException ioe) { err = ioe.Message; }
        catch (Exception ex) { err = "jumplist: " + ex.GetType().Name + ": " + ex.Message; }
        Program.ReplyFromWorker(rid, err == null, res, err);
      };
      try { w.Jobs.Add(job); }
      catch (InvalidOperationException) { return "jumplist: the reader was being replaced; ask again"; }
      result = Program.Deferred;
      return null;
    }

