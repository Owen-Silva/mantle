// JumpList.cs - the jump list behind a taskbar icon's right-click menu (wave 3, 2026-09-24).
//
// Owen: "i need to be able to right click the apps on the taskbar and have the same options
// regular windows shows". This file reads what Windows' own jump list shows for one app; the
// menu is ui/bar/jumplist.js, the main-process side lib/features/jumplist.js.
//
// ROUTE, all of it MEASURED on Owen's machine on 2026-09-24 (build 26200):
//   1. WHICH APP. The taskbar's own resolver, IApplicationResolver (CLSID 660b90c8, the Windows 8+
//      vtable, IID DE25675A): GetAppIDForWindow for a running app, GetAppIDForShortcut for a pinned
//      .lnk, GetBestShortcutAndAppIDForAppPath for a bare exe. Not a home-made guess, because the
//      guess is WRONG for Owen's own browser: its windows carry no AUMID and its exe path hashes to
//      nothing, but the resolver answers "Microsoft.AutoGenerated.{BBA25A7E-...}", whose jump list
//      file exists. Measured: 0.02-4 ms per window, 107 ms once for an auto-generated id (cold).
//   2. WHICH FILES. <Recent>\CustomDestinations\<h>.customDestinations-ms and
//      <Recent>\AutomaticDestinations\<h>.automaticDestinations-ms, where h is CRC-64 (reflected
//      polynomial 0x92C64265D32139A4, initial value all ones, no final xor) over the UTF-16LE of the
//      UPPER-CASED AppID, printed as lower-case hex WITHOUT leading zeros ("a61657a5e5dfbdc" is
//      Notepad's: 15 digits). Proved against Explorer, Edge, Notepad, PowerShell, Spotify and the
//      auto-generated browser id (tools: sidecar/test-jumplist.js checks every file it can resolve).
//   3. WHAT IS IN THEM. Custom: a 12-byte header, then categories (0 = named, 1 = a known one,
//      Frequent = 1 / Recent = 2, 2 = Tasks), each item a CLSID + a persisted object, so
//      OleLoadFromStream reads it exactly the way the app wrote it (IShellLink for every item seen
//      here), each category closed by 0xBABFFBAB. Automatic: an OLE compound file whose numbered
//      streams are shell links and whose "DestList" stream says which are pinned, how often and when
//      each was used. Both are copied into memory first (FileShare.ReadWrite|Delete): Owen's files are
//      never locked, written or deleted from here.
//
// Every read runs on this file's OWN STA thread, never on the ui lane: a jump list can name a file
// on a network drive, and the ui lane is where the bar's calls land. A stuck read gets a fresh
// thread for the next request (see Worker). Results are cached per AppID and dropped when either
// file's write time or length changes.
