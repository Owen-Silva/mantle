    static IApplicationResolver8 Resolver() {
      Worker w = _current;
      if (w == null) throw new InvalidOperationException("jumplist: resolver asked for off the jump-list thread");
      if (w.Resolver == null && w.ResolverError == null) {
        try {
          Type t = Type.GetTypeFromCLSID(ClsidResolver, true);
          w.Resolver = (IApplicationResolver8)Activator.CreateInstance(t);
        } catch (Exception ex) {
          w.ResolverError = "Windows' app resolver could not be created (" + ex.Message + ")";
        }
      }
      if (w.Resolver == null) throw new InvalidOperationException(w.ResolverError);
      return w.Resolver;
    }

    static string TakeString(IntPtr p) {
      if (p == IntPtr.Zero) return null;
      try { return Marshal.PtrToStringUni(p); } finally { Win32.CoTaskMemFree(p); }
    }

    /// The AppID Windows' taskbar would use, and how it was found. Throws the plain-words reason.
    static string ResolveAppId(Dictionary<string, object> req, out string how) {
      string app = Json.GetString(req, "app");
      if (!string.IsNullOrEmpty(app)) { how = "given"; return app; }
      string hwndS = Json.GetString(req, "hwnd");
      if (!string.IsNullOrEmpty(hwndS)) {
        IntPtr hwnd = Json.GetHwnd(req, "hwnd");
        IntPtr p; int prevented, isExplicit, embedded;
        int hr = Resolver().GetAppIDForWindow(hwnd, out p, out prevented, out isExplicit, out embedded);
        string id = TakeString(p);
        if (hr == 0 && !string.IsNullOrEmpty(id)) { how = isExplicit != 0 ? "window (explicit)" : "window"; return id; }
        if (string.IsNullOrEmpty(Json.GetString(req, "lnk")) && string.IsNullOrEmpty(Json.GetString(req, "exe")))
          throw new InvalidOperationException("Windows could not say which app window " + hwndS + " belongs to (0x" + hr.ToString("x8") + "); it may have closed");
      }
      string lnk = Json.GetString(req, "lnk");
      if (!string.IsNullOrEmpty(lnk)) {
        object raw;
        Guid iid = IidShellItem;
        int hr = Win32.SHCreateItemFromParsingName(lnk, IntPtr.Zero, ref iid, out raw);
        if (hr == 0 && raw != null) {
          IntPtr p;
          hr = Resolver().GetAppIDForShortcut((IShellItem)raw, out p);
          string id = TakeString(p);
          Marshal.ReleaseComObject(raw);
          if (hr == 0 && !string.IsNullOrEmpty(id)) { how = "shortcut"; return id; }
        }
        if (string.IsNullOrEmpty(Json.GetString(req, "exe")))
          throw new InvalidOperationException("Windows could not say which app the pinned shortcut belongs to (0x" + hr.ToString("x8") + ")");
      }
      string exe = Json.GetString(req, "exe");
      if (!string.IsNullOrEmpty(exe)) {
        IntPtr psi, p;
        int hr = Resolver().GetBestShortcutAndAppIDForAppPath(exe, out psi, out p);
        if (psi != IntPtr.Zero) Marshal.Release(psi);
        string id = TakeString(p);
        if (hr == 0 && !string.IsNullOrEmpty(id)) { how = "exe"; return id; }
        throw new InvalidOperationException("Windows could not say which app " + Path.GetFileName(exe) + " is (0x" + hr.ToString("x8") + ")");
      }
      throw new InvalidOperationException("jumplist needs app, hwnd, lnk or exe");
    }

    /// CRC-64 as the jump list file names use it (see the header for the proof).
    public static string HashOf(string appid) {
      ulong c = 0xFFFFFFFFFFFFFFFFUL;
      string up = appid.ToUpperInvariant();
      for (int i = 0; i < up.Length; i++) {
        c = Crc(c, (byte)(up[i] & 0xFF));
        c = Crc(c, (byte)(up[i] >> 8));
      }
      return c.ToString("x");
    }
    static ulong Crc(ulong c, byte b) {
      c ^= b;
      for (int k = 0; k < 8; k++) c = (c & 1UL) != 0 ? (c >> 1) ^ 0x92C64265D32139A4UL : (c >> 1);
      return c;
    }

