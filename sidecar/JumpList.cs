    static string StampOf(string path) {
      try {
        var fi = new FileInfo(path);
        return fi.Exists ? fi.LastWriteTimeUtc.Ticks + ":" + fi.Length : "-";
      } catch (Exception ex) { return "?" + ex.Message; }
    }

    static byte[] ReadShared(string path) {
      using (var fs = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete)) {
        var buf = new byte[fs.Length];
        int got = 0;
        while (got < buf.Length) {
          int n = fs.Read(buf, got, buf.Length - got);
          if (n <= 0) break;
          got += n;
        }
        if (got != buf.Length) Array.Resize(ref buf, got);
        return buf;
      }
    }

    static int ReadSetting(string name, int dflt) {
      try {
        using (var k = Registry.CurrentUser.OpenSubKey(@"Software\Microsoft\Windows\CurrentVersion\Explorer\Advanced")) {
          object v = k == null ? null : k.GetValue(name);
          if (v is int) return (int)v;
        }
      } catch (Exception) { }
      return dflt;
    }

    static object DoGet(Dictionary<string, object> req) {
      long t0 = Stopwatch.GetTimestamp();
      string how;
      string appid = ResolveAppId(req, out how);
      double resolveMs = Ms(t0);
      string hash = HashOf(appid);
      string dir = RecentDir(req);
      string customPath = Path.Combine(dir, "CustomDestinations", hash + ".customDestinations-ms");
      string autoPath = Path.Combine(dir, "AutomaticDestinations", hash + ".automaticDestinations-ms");
      int max = ReadSetting("Start_JumpListItems", MaxItemsDefault);
      if (max < 0 || max > 60) max = MaxItemsDefault;
      bool track = ReadSetting("Start_TrackDocs", 1) != 0;
      string stamp = StampOf(customPath) + "|" + StampOf(autoPath) + "|" + max + "|" + track;

      Cached hit;
      lock (_cache) _cache.TryGetValue(appid, out hit);
      if (hit != null && hit.Stamp == stamp && !Json.GetBool(req, "fresh", false)) {
        var copy = new Dictionary<string, object>(StringComparer.Ordinal);
        foreach (DictionaryEntry kv in hit.Result) copy[(string)kv.Key] = kv.Value;
        copy["how"] = how;
        copy["cached"] = true;
        copy["ms"] = Json.Obj("resolve", Math.Round(resolveMs, 2), "read", 0, "total", Math.Round(Ms(t0), 2));
        return copy;
      }

      long t1 = Stopwatch.GetTimestamp();
      var notes = new List<string>();
      var errors = new List<string>();
      var sections = new List<object>();
      List<KeyValuePair<string, List<Item>>> custom = null;
      var known = new List<int>();
      bool customFile = File.Exists(customPath), autoFile = File.Exists(autoPath);
      List<Item> auto = null;
      string destInfo = null;

      if (customFile) {
        try { custom = ReadCustom(customPath, known, false); }
        catch (Exception ex) { errors.Add("its tasks could not be read (" + Plain(ex) + ")"); }
      }
      if (autoFile) {
        try { auto = ReadAutomatic(autoPath, false, out destInfo); }
        catch (Exception ex) { errors.Add("its recent items could not be read (" + Plain(ex) + ")"); }
      }

      // Pinned first, then the known and named categories in the file's order, Tasks last,
      // which is the order Windows 11 draws them in.
      if (auto != null) {
        var pinned = auto.FindAll(delegate (Item i) { return i.Pinned; });
        pinned.Sort(delegate (Item a, Item b) { return a.PinAt.CompareTo(b.PinAt); });
        if (pinned.Count > 0) sections.Add(Section("Pinned", "pinned", pinned));
      }
      // No custom list at all: Windows shows Recent by default. A custom list shows only the
      // known categories the app asked for.
      if (custom == null && customFile == false) known.Add(2);
      List<Item> rest = auto == null ? new List<Item>() : auto.FindAll(delegate (Item i) { return !i.Pinned; });
      bool knownShown = false;
      if (custom != null || known.Count > 0) {
        var order = new List<KeyValuePair<string, List<Item>>>();
        if (custom != null) order.AddRange(custom);
        else order.Add(new KeyValuePair<string, List<Item>>("\u0001known:2", null));
        foreach (var cat in order) {
          if (cat.Key.StartsWith("\u0001known:")) {
            int which = int.Parse(cat.Key.Substring(7));
            if (which != 1 && which != 2) continue;
            if (!track) { if (!knownShown && rest.Count > 0) notes.Add("recent items are turned off in Windows Settings (Personalization > Start > Show recently opened items)"); knownShown = true; continue; }
            var list = new List<Item>(rest);
            if (which == 1) list.Sort(delegate (Item a, Item b) { int c = b.Score.CompareTo(a.Score); return c != 0 ? c : b.Count.CompareTo(a.Count); });
            else list.Sort(delegate (Item a, Item b) { return b.Used.CompareTo(a.Used); });
            if (list.Count > max) list.RemoveRange(max, list.Count - max);
            knownShown = true;
            if (list.Count > 0) sections.Add(Section(which == 1 ? "Frequent" : "Recent", which == 1 ? "frequent" : "recent", list));
          } else if (cat.Key == "\u0001tasks") {
            continue;   // drawn last, below
          } else if (cat.Value != null && cat.Value.Count > 0) {
            sections.Add(Section(cat.Key, "custom", cat.Value));
          }
        }
        if (custom != null) foreach (var cat in custom)
          if (cat.Key == "\u0001tasks" && cat.Value != null && cat.Value.Count > 0) sections.Add(Section("Tasks", "tasks", cat.Value));
      }

      string none = null;
      if (sections.Count == 0 && errors.Count == 0) {
        if (!customFile && !autoFile) none = "this app doesn't publish one";
        else if (!track && rest.Count > 0) none = "recent items are turned off in Windows Settings";
        else none = "the app's list is empty";
      }
      IDictionary res = Json.Obj(
        "ok", true, "appid", appid, "hash", hash,
        "files", Json.Obj("custom", customFile, "automatic", autoFile),
        "sections", sections,
        "none", none,
        "error", errors.Count > 0 ? string.Join("; ", errors.ToArray()) : null,
        "note", notes.Count > 0 ? string.Join("; ", notes.ToArray()) : null,
        "stamp", stamp,
        "max", max,
        "dest", destInfo);
      lock (_cache) {
        if (_cache.Count > 64) _cache.Clear();
        _cache[appid] = new Cached { Stamp = stamp, Result = res };
      }
      var outd = new Dictionary<string, object>(StringComparer.Ordinal);
      foreach (DictionaryEntry kv in res) outd[(string)kv.Key] = kv.Value;
      outd["how"] = how;
      outd["cached"] = false;
      outd["ms"] = Json.Obj("resolve", Math.Round(resolveMs, 2), "read", Math.Round(Ms(t1), 2), "total", Math.Round(Ms(t0), 2));
      return outd;
    }

    static double Ms(long t0) { return (Stopwatch.GetTimestamp() - t0) * 1000.0 / Stopwatch.Frequency; }

    static string Plain(Exception ex) {
      if (ex is FileNotFoundException) return "the file went away while it was read";
      if (ex is IOException) return "the file is busy: " + ex.Message;
      if (ex is UnauthorizedAccessException) return "access denied";
      return ex.Message;
    }

    static IDictionary Section(string name, string kind, List<Item> items) {
      var list = new List<object>();
      foreach (Item i in items) {
        if (i.Separator) { list.Add(Json.Obj("sep", true)); continue; }
        list.Add(Json.Obj("title", i.Title, "tip", i.Tip, "icon", i.Icon, "item", i.Token, "kind", i.Kind,
                          "pinned", i.Pinned, "canRemove", i.CanRemove));
      }
      return Json.Obj("name", name, "kind", kind, "items", list);
    }

