    /// Keys: a category's name, "\u0001known:N", or "\u0001tasks". `keep` holds on to the loaded
    /// COM objects (for opening one); otherwise they are released as soon as they are described.
    static List<KeyValuePair<string, List<Item>>> ReadCustom(string path, List<int> known, bool keep) {
      byte[] b = ReadShared(path);
      if (b.Length < 12) throw new InvalidDataException("the file is " + b.Length + " bytes, shorter than its header");
      int version = BitConverter.ToInt32(b, 0);
      if (version != 2) throw new InvalidDataException("format version " + version + " (only 2 is known)");
      int cats = BitConverter.ToInt32(b, 4);
      if (cats < 0 || cats > 200) throw new InvalidDataException("it claims " + cats + " categories");
      IStream stm = N.SHCreateMemStream(b, (uint)b.Length);
      if (stm == null) throw new InvalidDataException("no memory stream");
      IntPtr posBuf = Marshal.AllocHGlobal(8);
      var outList = new List<KeyValuePair<string, List<Item>>>();
      try {
        int pos = 12;
        for (int c = 0; c < cats; c++) {
          Need(b, pos, 4);
          int type = BitConverter.ToInt32(b, pos); pos += 4;
          string key; int count = 0;
          if (type == 1) {
            Need(b, pos, 4);
            int which = BitConverter.ToInt32(b, pos); pos += 4;
            known.Add(which);
            outList.Add(new KeyValuePair<string, List<Item>>("\u0001known:" + which, null));
            Need(b, pos, 4);
            if (BitConverter.ToUInt32(b, pos) != FooterMagic) throw new InvalidDataException("category " + c + " has no end mark");
            pos += 4;
            continue;
          } else if (type == 0) {
            Need(b, pos, 2);
            int nlen = BitConverter.ToUInt16(b, pos); pos += 2;
            Need(b, pos, nlen * 2);
            key = Indirect(Encoding.Unicode.GetString(b, pos, nlen * 2)); pos += nlen * 2;
            Need(b, pos, 4);
            count = BitConverter.ToInt32(b, pos); pos += 4;
          } else if (type == 2) {
            key = "\u0001tasks";
            Need(b, pos, 4);
            count = BitConverter.ToInt32(b, pos); pos += 4;
          } else throw new InvalidDataException("category " + c + " has unknown type " + type);
          if (count < 0 || count > 500) throw new InvalidDataException("category " + c + " claims " + count + " items");
          var items = new List<Item>();
          for (int i = 0; i < count; i++) {
            stm.Seek(pos, 0, IntPtr.Zero);
            object obj;
            Guid iu = IidUnknown;
            int hr = N.OleLoadFromStream(stm, ref iu, out obj);
            if (hr != 0 || obj == null) throw new InvalidDataException("item " + i + " of category " + c + " did not load (0x" + hr.ToString("x8") + ")");
            stm.Seek(0, 1, posBuf);
            pos = (int)Marshal.ReadInt64(posBuf);
            Item it = DescribeLink(obj, type == 2 ? "task" : "link");
            it.Token = "c:" + c + ":" + i;
            if (keep) it.Obj = obj; else Marshal.ReleaseComObject(obj);
            items.Add(it);
          }
          Need(b, pos, 4);
          if (BitConverter.ToUInt32(b, pos) != FooterMagic) throw new InvalidDataException("category " + c + " has no end mark");
          pos += 4;
          outList.Add(new KeyValuePair<string, List<Item>>(key, items));
        }
      } finally {
        Marshal.FreeHGlobal(posBuf);
        Marshal.ReleaseComObject(stm);
      }
      return outList;
    }

    static void Need(byte[] b, int pos, int n) {
      if (pos < 0 || n < 0 || pos + n > b.Length) throw new InvalidDataException("the file ends early (at byte " + pos + ")");
    }

    /// "@%SystemRoot%\\...dll,-123" and "ms-resource:" titles, as the app meant them.
    static string Indirect(string s) {
      if (string.IsNullOrEmpty(s) || s[0] != '@') return s;
      var sb = new StringBuilder(512);
      return N.SHLoadIndirectString(s, sb, sb.Capacity, IntPtr.Zero) == 0 ? sb.ToString() : s;
    }

    static string PropString(Win32.IPropertyStore ps, Guid fmtid, uint pid) {
      var key = new Win32.PROPERTYKEY { fmtid = fmtid, pid = pid };
      var pv = new Win32.PROPVARIANT();
      try {
        ps.GetValue(ref key, out pv);
        if (pv.vt == 31 && pv.p != IntPtr.Zero) return Marshal.PtrToStringUni(pv.p);   // VT_LPWSTR
        if (pv.vt == 11) return pv.p != IntPtr.Zero && (pv.p.ToInt64() & 0xFFFF) != 0 ? "true" : "false"; // VT_BOOL
        return null;
      } catch (Exception) { return null; }
      finally { try { Win32.PropVariantClear(ref pv); } catch (Exception) { } }
    }

    static Item DescribeLink(object obj, string kind) {
      var it = new Item { Kind = kind };
      var ps = obj as Win32.IPropertyStore;
      if (ps != null) {
        if (PropString(ps, FmtidAppUserModel, 6) == "true") { it.Separator = true; return it; }
        it.Title = Indirect(PropString(ps, FmtidTitle, 2));
      }
      var link = obj as IShellLinkW;
      if (link == null) {
        it.Title = it.Title ?? "(an item Mantle cannot read)";
        return it;
      }
      var sb = new StringBuilder(1040);
      string target = "", args = "", iconPath = "";
      int iconIndex = 0;
      try { link.GetPath(sb, sb.Capacity, IntPtr.Zero, 0); target = sb.ToString(); } catch (Exception) { }
      try { sb.Length = 0; link.GetArguments(sb, sb.Capacity); args = sb.ToString(); } catch (Exception) { }
      try { sb.Length = 0; link.GetIconLocation(sb, sb.Capacity, out iconIndex); iconPath = Environment.ExpandEnvironmentVariables(sb.ToString()); } catch (Exception) { }
      IntPtr pidl = IntPtr.Zero;
      try {
        try { link.GetIDList(out pidl); } catch (Exception) { }
        if (string.IsNullOrEmpty(it.Title)) {
          try { sb.Length = 0; link.GetDescription(sb, sb.Capacity); it.Title = Indirect(sb.ToString()); } catch (Exception) { }
        }
        if (string.IsNullOrEmpty(it.Title) && pidl != IntPtr.Zero) it.Title = PidlName(pidl, Win32.SIGDN_NORMALDISPLAY);
        if (string.IsNullOrEmpty(it.Title)) it.Title = target.Length > 0 ? Path.GetFileNameWithoutExtension(target) : "(untitled)";
        it.Tip = (target.Length > 0 ? target : (pidl != IntPtr.Zero ? PidlName(pidl, Win32.SIGDN_DESKTOPABSOLUTEPARSING) : "")) +
                 (args.Length > 0 ? " " + (args.Length > 160 ? args.Substring(0, 160) + "..." : args) : "");
        it.Icon = IconFor(iconPath, iconIndex, target, pidl);
      } finally {
        if (pidl != IntPtr.Zero) Win32.CoTaskMemFree(pidl);
      }
      return it;
    }

    static string PidlName(IntPtr pidl, uint sigdn) {
      IntPtr p;
      if (Win32.SHGetNameFromIDList(pidl, sigdn, out p) != 0) return null;
      return TakeString(p);
    }

    /// An icon without touching a network drive: an explicit icon file, else a LOCAL target's own
    /// icon, else the icon of its type (by extension, no disk access at all).
    static string IconFor(string iconPath, int iconIndex, string target, IntPtr pidl) {
      string key = iconPath.Length > 0 ? iconPath + "," + iconIndex : target;
      bool local = IsLocal(iconPath.Length > 0 ? iconPath : target);
      if (!local && target.Length > 0) key = "type:" + Path.GetExtension(target);
      string hit;
      lock (_icons) if (!string.IsNullOrEmpty(key) && _icons.TryGetValue(key, out hit)) return hit;
      string url = null;
      try {
        if (iconPath.Length > 0 && local) {
          IntPtr large;
          if (N.ExtractIconEx(iconPath, iconIndex, out large, IntPtr.Zero, 1) > 0 && large != IntPtr.Zero) {
            try { url = Icons.FromHIcon(large); } finally { Win32.DestroyIcon(large); }
          }
        }
        if (url == null && local && pidl != IntPtr.Zero) url = FromPidl(pidl);
        if (url == null && target.Length > 0) url = ByType(target, false);
        if (url == null && pidl != IntPtr.Zero && !local && target.Length == 0) url = FromPidl(pidl);   // a shell item, not a file
      } catch (Exception) { url = null; }
      if (!string.IsNullOrEmpty(key)) lock (_icons) { if (_icons.Count > 400) _icons.Clear(); _icons[key] = url; }
      return url;
    }

    static bool IsLocal(string path) {
      if (string.IsNullOrEmpty(path) || path.Length < 3 || path[1] != ':' || path[2] != '\\') return false;
      try { return N.GetDriveType(path.Substring(0, 3)) == 3; }   // DRIVE_FIXED
      catch (Exception) { return false; }
    }

    static string FromPidl(IntPtr pidl) {
      var info = new Win32.SHFILEINFO();
      IntPtr res = Win32.SHGetFileInfoPidl(pidl, 0, ref info, (uint)Marshal.SizeOf(typeof(Win32.SHFILEINFO)),
                                           Win32.SHGFI_PIDL | Win32.SHGFI_ICON | Win32.SHGFI_LARGEICON);
      if (res == IntPtr.Zero || info.hIcon == IntPtr.Zero) return null;
      try { return Icons.FromHIcon(info.hIcon); } finally { Win32.DestroyIcon(info.hIcon); }
    }

    static string ByType(string path, bool folder) {
      string key = "type:" + (folder ? "<dir>" : Path.GetExtension(path));
      string hit;
      lock (_icons) if (_icons.TryGetValue(key, out hit)) return hit;
      var info = new Win32.SHFILEINFO();
      IntPtr res = N.SHGetFileInfo(folder ? "folder" : "x" + Path.GetExtension(path), folder ? 0x10u : 0x80u, ref info,
                                   (uint)Marshal.SizeOf(typeof(Win32.SHFILEINFO)),
                                   Win32.SHGFI_ICON | Win32.SHGFI_LARGEICON | Win32.SHGFI_USEFILEATTRIBUTES);
      string url = null;
      if (res != IntPtr.Zero && info.hIcon != IntPtr.Zero) {
        try { url = Icons.FromHIcon(info.hIcon); } finally { Win32.DestroyIcon(info.hIcon); }
      }
      lock (_icons) _icons[key] = url;
      return url;
    }

